/* ───── Extract department from text ───── */
function extractDepartment(text: string): string | null {
  // (XX) pattern
  const match = text.match(/\((\d{2,3}|2[AB])\)/);
  if (match && DEPT_MAP[match[1]]) return match[1];

  // Postal code (5 digits)
  const postalMatch = text.match(/\b((?:0[1-9]|[1-8]\d|9[0-5]|97[1-6]|2[AB])\d{3})\b/);
  if (postalMatch) {
    const code = postalMatch[1];
    if (code.startsWith('20')) return parseInt(code) >= 20200 ? '2B' : '2A';
    if (code.startsWith('97')) {
      const d = code.substring(0, 3);
      return DEPT_MAP[d] ? d : null;
    }
    const d = code.substring(0, 2);
    return DEPT_MAP[d] ? d : null;
  }

  return null;
}

async function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const limit = parseInt(args.find((a) => a.startsWith('--limit='))?.split('=')[1] || '10000');

  console.log(`\nBackfill departments — ${dryRun ? 'DRY RUN' : 'LIVE'} — limit=${limit}\n`);

  // Find all marchés with department='00' or empty
  const marches = await prisma.marche.findMany({
    where: {
      OR: [
        { department: '00' },
        { department: '' },
        { department: 'nan' },
      ],
    },
    select: { id: true, buyer: true, title: true, department: true, source: true },
    take: limit,
  });

  console.log(`Found ${marches.length} marchés with missing department\n`);

  let updated = 0;
  let skipped = 0;

  for (const m of marches) {
    const dept = extractDepartment(m.buyer) || extractDepartment(m.title);
    if (!dept) {
      skipped++;
      continue;
    }

    const info = DEPT_MAP[dept];
    if (!info) {
      skipped++;
      continue;
    }

    if (dryRun) {
      console.log(`[DRY] ${m.source} | "${m.buyer.slice(0, 60)}" → ${dept} (${info.name})`);
    } else {
      await prisma.marche.update({
        where: { id: m.id },
        data: {
          department: dept,
          departmentName: info.name,
          region: info.region,
        },
      });
    }
    updated++;
  }

  console.log(`\nDone: ${updated} updated, ${skipped} skipped (no dept found in text)`);
  await prisma.$disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
